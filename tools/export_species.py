#!/usr/bin/env python3
"""Export the species list from the handheld Pokédex's dex.db into dexsync.

    python3 tools/export_species.py ../pokedex/data/dex.db

Writes crates/core/data/species.tsv (id, name, generation, types), which is
compiled into dexsync-core. dex.db is built from PokéAPI by
../pokedex/tools/build_dex.py and opened read-only here.
"""
import sqlite3
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates/core/data/species.tsv"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    db = sqlite3.connect(f"file:{sys.argv[1]}?mode=ro", uri=True)
    rows = db.execute("SELECT id, display, generation, types FROM species ORDER BY id").fetchall()
    ids = [r[0] for r in rows]
    if ids != list(range(1, len(ids) + 1)):
        sys.exit(f"dex.db has gaps (got {len(ids)} species); rebuild it with build_dex.py")
    with OUT.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# id\tname\tgeneration\ttypes  (generated by tools/export_species.py from PokéAPI data)\n")
        for sid, name, gen, types in rows:
            f.write(f"{sid}\t{name}\t{gen}\t{types}\n")
    print(f"wrote {len(rows)} species to {OUT}")


if __name__ == "__main__":
    main()
